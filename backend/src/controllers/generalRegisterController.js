const User = require('../models/User');
const Counter = require('../models/Counter');
const Enrollment = require('../models/Enrollment');
const TeacherAssignment = require('../models/TeacherAssignment');
const Class = require('../models/Class');
const AcademicYear = require('../models/AcademicYear');

const getNextSequenceValue = async (sequenceName) => {
  const sequenceDocument = await Counter.findOneAndUpdate(
    { id: sequenceName },
    { $inc: { seq: 1 } },
    { new: true, upsert: true }
  );
  return sequenceDocument.seq;
};

exports.registerStudent = async (req, res) => {
  try {
    const { studentId: customStudentId, name, email, password: customPassword, gender, dateOfBirth, contactDetails, classId } = req.body;
    
    // Authorization check
    if (req.user.role !== 'teacher' && req.user.role !== 'principal') {
      return res.status(403).json({ success: false, message: 'Unauthorized' });
    }

    const cls = await Class.findById(classId);
    if (!cls) return res.status(404).json({ success: false, message: 'Class not found' });

    // Strict class-section permission for Teacher
    if (req.user.role === 'teacher') {
      if (!cls.teacherId || cls.teacherId.toString() !== req.user._id.toString()) {
        return res.status(403).json({ success: false, message: 'Only the designated Class Teacher can add students to this class.' });
      }
    }

    const currentYear = new Date().getFullYear();
    const grSeq = await getNextSequenceValue('grNumber');
    const studentSeq = await getNextSequenceValue(`studentId_${classId}`);
    
    const grNumber = `GR${currentYear}${String(grSeq).padStart(4, '0')}`;
    const autoGeneratedId = `${currentYear}${cls.standard}${cls.section}${String(studentSeq).padStart(2, '0')}`;
    const studentId = customStudentId ? customStudentId : autoGeneratedId;

    // Explicitly check for duplicate student ID to give a clear error
    if (customStudentId) {
      const existing = await User.findOne({ studentId: customStudentId });
      if (existing) {
        return res.status(400).json({ success: false, message: 'An account with that Student ID already exists.' });
      }
    }

    // Create user
    let tempPassword = customPassword;
    if (!tempPassword) {
      const generateSecureTempPassword = require("../utils/generatePassword");
      tempPassword = generateSecureTempPassword();
    }
    const newUser = await User.create({
      name,
      email: email || `${studentId.toLowerCase()}.${grNumber.toLowerCase()}@studymate.school`,
      password: tempPassword,
      mustChangePassword: true,
      role: 'student',
      studentId,
      grNumber,
      gender,
      dateOfBirth,
      contactDetails,
      schoolId: req.user.schoolId
    });

    // Create Enrollment
    const activeYear = await AcademicYear.findOne({ status: 'active' }) || { _id: null };
    await Enrollment.create({
      studentId: newUser._id,
      academicYearId: activeYear._id,
      classId: classId,
      schoolId: req.user.schoolId,
      type: 'new_admission',
      status: 'active'
    });

    // Add to class
    await Class.findByIdAndUpdate(classId, { $push: { students: newUser._id } });

    res.status(201).json({
      success: true,
      message: 'Student registered successfully',
      data: {
        studentId: newUser.studentId,
        grNumber: newUser.grNumber,
        tempPassword
      }
    });

  } catch (error) {
    if (error.code === 11000) {
      const field = Object.keys(error.keyValue)[0];
      return res.status(400).json({ success: false, message: `An account with that ${field} already exists.` });
    }
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.getStudents = async (req, res) => {
  try {
    let students = [];
    if (req.user.role === 'principal') {
      students = await User.find({ role: 'student', schoolId: req.user.schoolId });
    } else if (req.user.role === 'teacher') {
      const classes = await Class.find({ teacherId: req.user._id });
      const studentIds = classes.flatMap(c => c.students);
      students = await User.find({ _id: { $in: studentIds }, role: 'student', schoolId: req.user.schoolId });
    }
    res.status(200).json({ success: true, data: students });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.updateStudent = async (req, res) => {
  try {
    const { id } = req.params;
    const { studentId, name, email, password, gender, classId } = req.body;
    
    // Find student
    const student = await User.findOne({ _id: id, role: 'student', schoolId: req.user.schoolId });
    if (!student) {
      return res.status(404).json({ success: false, message: 'Student not found' });
    }

    if (req.user.role === 'teacher') {
      const cls = await Class.findOne({ students: id });
      if (!cls || !cls.teacherId || cls.teacherId.toString() !== req.user._id.toString()) {
        return res.status(403).json({ success: false, message: 'Only the designated Class Teacher can edit students.' });
      }
      if (classId && cls._id.toString() !== classId.toString()) {
        const newCls = await Class.findById(classId);
        if (!newCls || !newCls.teacherId || newCls.teacherId.toString() !== req.user._id.toString()) {
          return res.status(403).json({ success: false, message: 'Only the designated Class Teacher can move students to that class.' });
        }
      }
    }

    // Update user info
    student.studentId = studentId || student.studentId;
    student.name = name || student.name;
    student.email = email || student.email;
    student.gender = gender || student.gender;
    if (password) {
      student.password = password;
    }
    await student.save();

    if (classId) {
      const activeYear = await AcademicYear.findOne({ status: 'active' });
      if (activeYear) {
        const enrollment = await Enrollment.findOne({ studentId: id, academicYearId: activeYear._id });
        if (enrollment && enrollment.classId.toString() !== classId) {
          await Class.findByIdAndUpdate(enrollment.classId, { $pull: { students: id } });
          enrollment.classId = classId;
          await enrollment.save();
          await Class.findByIdAndUpdate(classId, { $addToSet: { students: id } });
        }
      }
    }
    res.status(200).json({ success: true, message: 'Student updated successfully', data: student });
  } catch (error) {
    if (error.code === 11000) {
      const field = Object.keys(error.keyValue)[0];
      return res.status(400).json({ success: false, message: `An account with that ${field} already exists.` });
    }
    res.status(500).json({ success: false, message: error.message });
  }
};

exports.deleteStudent = async (req, res) => {
  try {
    const { id } = req.params;
    const student = await User.findOne({ _id: id, role: 'student', schoolId: req.user.schoolId });
    if (!student) {
      return res.status(404).json({ success: false, message: 'Student not found' });
    }

    if (req.user.role === 'teacher') {
      const cls = await Class.findOne({ students: id });
      if (!cls || !cls.teacherId || cls.teacherId.toString() !== req.user._id.toString()) {
        return res.status(403).json({ success: false, message: 'Only the designated Class Teacher can delete students.' });
      }
    }

    // Fully delete for this demo
    await User.findByIdAndDelete(id);

    res.status(200).json({ success: true, message: 'Student deleted successfully' });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};
